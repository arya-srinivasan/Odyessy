"""Data access layer for TravelAgntcy agents.

Loads mock datasets generated by travel/data/generate.py and exposes
search and utility functions.
"""

from datetime import date, timedelta
import json
from pathlib import Path
from typing import Any

# Resolve path to travel/data directory relative to this file
DATA_DIR = Path(__file__).resolve().parent.parent / "data"


def _load_json(filename: str) -> Any:
    path = DATA_DIR / filename
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


# Module-level cached datasets
CITIES: dict[str, dict[str, Any]] = _load_json("cities.json")
FLIGHTS: list[dict[str, Any]] = _load_json("flights.json")
HOTELS: list[dict[str, Any]] = _load_json("hotels.json")
ACTIVITIES: list[dict[str, Any]] = _load_json("activities.json")
TRAINS: list[dict[str, Any]] = _load_json("trains.json")
FORECAST_PATTERN: dict[str, list[str]] = _load_json("forecast_pattern.json")


def resolve_city(text: str) -> dict[str, Any] | None:
    """Resolve city record for 'tokyo', 'HND', 'Tokyo, Japan', 'NYC', etc."""
    if not text:
        return None

    query = text.strip().lower()
    if query in ("nyc", "new york city"):
        query = "new york"

    # 1. Exact match on airport code
    for code, info in CITIES.items():
        if query == code.lower():
            return dict(info)

    # 2. Exact match on city name
    for info in CITIES.values():
        if query == info["city"].lower():
            return dict(info)

    # 3. Substring match (e.g. "Tokyo, Japan" -> "Tokyo")
    for info in CITIES.values():
        city_lower = info["city"].lower()
        if city_lower in query or query in city_lower:
            return dict(info)

    return None


def search_flights(
    origin: str,
    dest: str,
    max_price: float | None = None,
    exclude_ids: list[str] | None = None,
    limit: int = 5,
) -> list[dict[str, Any]]:
    """Return cheapest flights matching origin/dest, skipping excluded IDs."""
    orig_city = resolve_city(origin)
    dest_city = resolve_city(dest)

    orig_codes = {origin.lower()}
    if orig_city:
        orig_codes.update({orig_city["airport"].lower(), orig_city["city"].lower()})

    dest_codes = {dest.lower()}
    if dest_city:
        dest_codes.update({dest_city["airport"].lower(), dest_city["city"].lower()})

    excluded = set(exclude_ids or [])

    matching: list[dict[str, Any]] = []
    for f in FLIGHTS:
        if f["id"] in excluded:
            continue

        f_orig = {f["origin"].lower(), f["origin_city"].lower()}
        f_dest = {f["destination"].lower(), f["destination_city"].lower()}

        if f_orig.intersection(orig_codes) and f_dest.intersection(dest_codes):
            matching.append(dict(f))

    if not matching:
        return []

    # Filter by max_price; fall back to all matches if filter empties list
    candidates = matching
    if max_price is not None:
        filtered = [f for f in matching if f["price_usd"] <= max_price]
        if filtered:
            candidates = filtered

    candidates.sort(key=lambda x: x["price_usd"])
    return candidates[:limit]


def search_hotels(
    city: str,
    nights: int = 1,
    max_per_night: float | None = None,
    area: str | None = None,
    limit: int = 6,
) -> list[dict[str, Any]]:
    """Return best-rated hotels for city, enriched with nights and total_usd."""
    city_record = resolve_city(city)
    target_city = city_record["city"].lower() if city_record else city.strip().lower()

    city_hotels = [
        dict(h) for h in HOTELS if h["city"].lower() == target_city
    ]
    if not city_hotels:
        return []

    # Optional area filter (falls back if empty)
    candidates = city_hotels
    if area:
        by_area = [h for h in candidates if h["area"].lower() == area.strip().lower()]
        if by_area:
            candidates = by_area

    # Optional price filter (falls back if empty)
    if max_per_night is not None:
        by_price = [h for h in candidates if h["price_per_night_usd"] <= max_per_night]
        if by_price:
            candidates = by_price

    # Sort best rated first
    candidates.sort(key=lambda x: x["rating"], reverse=True)

    results = []
    for h in candidates[:limit]:
        item = dict(h)
        item["nights"] = nights
        item["total_usd"] = item["price_per_night_usd"] * nights
        results.append(item)

    return results


def cheaper_hotels(hotel: dict[str, Any], min_rating: float) -> list[dict[str, Any]]:
    """Return cheaper alternatives in the same city meeting min_rating (smallest downgrade first)."""
    city = hotel["city"]
    current_price = hotel["price_per_night_usd"]
    nights = hotel.get("nights", 1)

    matching = [
        dict(h)
        for h in HOTELS
        if h["city"].lower() == city.lower()
        and h["price_per_night_usd"] < current_price
        and h["rating"] >= min_rating
    ]

    # Smallest price downgrade first
    matching.sort(key=lambda x: x["price_per_night_usd"], reverse=True)

    for h in matching:
        h["nights"] = nights
        h["total_usd"] = h["price_per_night_usd"] * nights

    return matching


def search_activities(
    city: str, interests: list[str] | None = None
) -> list[dict[str, Any]]:
    """Return activities for city: matching interests first, then rating descending."""
    city_record = resolve_city(city)
    target_city = city_record["city"].lower() if city_record else city.strip().lower()

    candidates = [
        dict(a) for a in ACTIVITIES if a["city"].lower() == target_city
    ]
    if not candidates:
        return []

    interest_set = {i.lower() for i in (interests or [])}

    def sort_key(act: dict[str, Any]):
        matches_interest = 1 if act.get("category", "").lower() in interest_set else 0
        return (matches_interest, act.get("rating", 0.0))

    candidates.sort(key=sort_key, reverse=True)
    return candidates


def search_trains(from_city: str, to_city: str) -> list[dict[str, Any]]:
    """Return all rail departures connecting from_city to to_city."""
    c_from = resolve_city(from_city)
    c_to = resolve_city(to_city)

    src = c_from["city"].lower() if c_from else from_city.strip().lower()
    dst = c_to["city"].lower() if c_to else to_city.strip().lower()

    return [
        dict(t)
        for t in TRAINS
        if t["from_city"].lower() == src and t["to_city"].lower() == dst
    ]


def rail_alternatives(origin: str, dest: str) -> list[dict[str, Any]]:
    """Return direct rail route if available, otherwise day trips from the destination."""
    direct = search_trains(origin, dest)
    if direct:
        return direct

    c_dest = resolve_city(dest)
    target_dest = c_dest["city"].lower() if c_dest else dest.strip().lower()

    # Day trips departing from destination
    return [
        dict(t)
        for t in TRAINS
        if t["from_city"].lower() == target_dest
    ]


def trip_days(depart: str, return_date: str) -> list[str]:
    """Return list of inclusive ISO dates (YYYY-MM-DD), capped at 14 days."""
    start = date.fromisoformat(depart)
    end = date.fromisoformat(return_date)

    if end < start:
        return [depart]

    days = []
    curr = start
    while curr <= end and len(days) < 14:
        days.append(curr.isoformat())
        curr += timedelta(days=1)

    return days


def mock_forecast(
    city: str, days: list[str], rain_days: list[int] | None = None
) -> list[dict[str, Any]]:
    """Return mock forecast entries: [{"day", "date", "sky", "outdoor_ok"}]."""
    city_record = resolve_city(city)
    target_city = city_record["city"] if city_record else city

    pattern = FORECAST_PATTERN.get(target_city, ["sunny"] * 7)
    rain_set = set(rain_days or [])

    forecast = []
    for i, date_str in enumerate(days):
        if i in rain_set:
            sky = "rain"
        else:
            sky = pattern[i % len(pattern)]

        forecast.append({
            "day": i,
            "date": date_str,
            "sky": sky,
            "outdoor_ok": (sky != "rain"),
        })

    return forecast


def outdoor_on_rain_days(
    forecast: list[dict[str, Any]], days: list[list[dict[str, Any]]] | list[dict[str, Any]]
) -> int:
    """Return count of outdoor activities scheduled on rainy days."""
    rainy_day_indices = {
        item["day"] for item in forecast if not item.get("outdoor_ok", True)
    }

    clash_count = 0
    for day_idx, activities in enumerate(days):
        if day_idx in rainy_day_indices:
            # Handle whether days is a list of activity lists or list of activity objects
            if isinstance(activities, list):
                for act in activities:
                    if not act.get("indoor", False):
                        clash_count += 1
            elif isinstance(activities, dict):
                for act in activities.get("activities", []):
                    if not act.get("indoor", False):
                        clash_count += 1

    return clash_count

